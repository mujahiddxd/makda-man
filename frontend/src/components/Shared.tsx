import React from "react";
import type { RiskLevel, Strategy } from "@/lib/types";

export function RiskBadge({
  level,
  score,
  className = "",
}: {
  level: RiskLevel;
  score?: number;
  className?: string;
}) {
  const styles: Record<RiskLevel, string> = {
    critical: "bg-[#FDECEC] text-[#D64545] border-2 border-[#D64545] font-extrabold",
    high: "bg-[#F2A58B] text-[#17151F] border border-[#17151F]/40 font-bold",
    medium: "bg-[#F9D56E] text-[#17151F] border border-[#17151F]/40 font-bold",
    low: "bg-[#A8CCF4] text-[#17151F] border border-[#17151F]/40 font-bold",
    none: "bg-[#B9E4A1] text-[#17151F] border border-[#17151F]/40 font-bold",
  };

  return (
    <span
      className={`inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs uppercase tracking-wider ${styles[level] || styles.none} ${className}`}
    >
      <span>{level}</span>
      {score !== undefined && (
        <span className="font-mono text-[11px] px-1.5 py-0.2 bg-black/10 rounded-full">
          {score}
        </span>
      )}
    </span>
  );
}

export function ProvenanceTag({
  provenance,
  className = "",
}: {
  provenance: "ai" | "evidence" | "derived";
  className?: string;
}) {
  const info = {
    ai: {
      label: "Gemma 4",
      icon: "✨",
      bg: "bg-[#C3B1F5] text-[#17151F] border border-[#17151F]/30",
      tooltip: "Generated by Gemma 4 (instruction-tuned model via Google AI Studio)",
    },
    evidence: {
      label: "Evidence",
      icon: "✓",
      bg: "bg-[#B9E4A1] text-[#17151F] border border-[#17151F]/30",
      tooltip: "Direct evidence observed from PyPI, OSV, AST inspection, or sandbox tests",
    },
    derived: {
      label: "Computed",
      icon: "⚙",
      bg: "bg-white text-[#17151F] border border-[#17151F]/30 shadow-xs",
      tooltip: "Computed deterministically by DepExit pipeline logic",
    },
  }[provenance] || {
    label: provenance,
    icon: "•",
    bg: "bg-white text-[#17151F] border border-gray-300",
    tooltip: "",
  };

  return (
    <span
      title={info.tooltip}
      className={`inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-semibold select-none cursor-help transition-transform hover:scale-105 ${info.bg} ${className}`}
    >
      <span className="text-xs">{info.icon}</span>
      <span>{info.label}</span>
    </span>
  );
}

export function StrategyChip({
  strategy,
  packageTarget,
  className = "",
}: {
  strategy: Strategy;
  packageTarget?: string;
  className?: string;
}) {
  const styles: Record<Strategy, string> = {
    replace: "bg-[#A8CCF4] text-[#17151F] border border-[#17151F]/30",
    upgrade: "bg-[#B9E4A1] text-[#17151F] border border-[#17151F]/30",
    stdlib: "bg-[#C3B1F5] text-[#17151F] border border-[#17151F]/30",
    remove: "bg-[#F2A58B] text-[#17151F] border border-[#17151F]/30",
    declare: "bg-[#F9D56E] text-[#17151F] border border-[#17151F]/30",
    keep: "bg-white text-[#17151F] border border-[#17151F]/30",
  };

  return (
    <span
      className={`inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-bold ${styles[strategy] || styles.keep} ${className}`}
    >
      <span className="capitalize">{strategy}</span>
      {packageTarget && (
        <span className="font-mono text-xs font-normal">→ {packageTarget}</span>
      )}
    </span>
  );
}
