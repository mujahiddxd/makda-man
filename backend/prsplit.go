package main

// Split mode: deliver the migration as a stack of small pull requests instead of one large one.
//
// The AI service writes data/<id>/split.json at the capsule stage: PR 1 holds the quick wins (manifest-only changes),
// then one PR per code rewrite in priority order, plus the manifest content of every step under data/<id>/split/<k>/.
// Each PR is based on the previous one's branch (stacked), so shared files such as requirements.txt never conflict;
// when a PR is merged, GitHub retargets the next one. A PR can only be based on a branch of the same repository, so
// split mode needs push access (no fork). Only the final state ran in the sandbox, which every part says.

import (
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"
)

const stackPlaceholder = "<!-- depexit-stack -->"

// errSplitNeedsPush: stacked PRs must live in the target repository, which the token cannot push to.
type errSplitNeedsPush struct{ repo string }

func (e errSplitNeedsPush) Error() string {
	return fmt.Sprintf("split pull requests need write access to %s (a stacked PR cannot be based on a branch in your "+
		"fork); open a single pull request instead, or analyse a repository you can push to", e.repo)
}

type splitFile struct {
	Path   string `json:"path"`
	Source string `json:"source"` // "migrated" (the tested workspace) or "split" (data/<id>/split/<k>/)
}

type splitGroup struct {
	Index         int         `json:"index"`
	Kind          string      `json:"kind"` // quick_wins | rewrite
	Dependencies  []string    `json:"dependencies"`
	Files         []splitFile `json:"files"`
	Insertions    int         `json:"insertions"`
	Deletions     int         `json:"deletions"`
	Label         string      `json:"label"`
	RiskReduction int         `json:"risk_reduction"`
	Title         string      `json:"title"`
}

type prStack struct {
	Available bool         `json:"available"`
	Reason    string       `json:"reason,omitempty"`
	Note      string       `json:"note,omitempty"`
	PRs       []*prPlan    `json:"prs"`
	Groups    []splitGroup `json:"groups,omitempty"`
}

// buildSplitPlan turns split.json into one prPlan per part. `single` is the one-PR plan (for shared facts).
func (a *API) buildSplitPlan(id string, single *prPlan) *prStack {
	dir := a.store.jobDir(id)
	raw, err := os.ReadFile(filepath.Join(dir, "split.json"))
	if err != nil {
		return &prStack{Reason: "This analysis has no split plan (it was made before split pull requests existed); re-run it to split."}
	}
	var sp struct {
		Available bool         `json:"available"`
		Reason    *string      `json:"reason"`
		Note      string       `json:"note"`
		Groups    []splitGroup `json:"groups"`
	}
	if err := json.Unmarshal(raw, &sp); err != nil {
		return &prStack{Reason: "split.json is not valid JSON"}
	}
	if !sp.Available {
		r := "Splitting is not possible for this migration."
		if sp.Reason != nil {
			r = *sp.Reason
		}
		return &prStack{Reason: r}
	}
	byDep := map[string]prRiskDep{}
	for _, d := range single.riskIn.Deps {
		byDep[d.Name] = d
	}
	n := len(sp.Groups)
	st := &prStack{Available: true, Note: sp.Note, Groups: sp.Groups}
	for _, g := range sp.Groups {
		in := prRiskInput{Verdict: single.riskIn.Verdict, MigratedStatus: single.riskIn.MigratedStatus,
			MigratedTotal: single.riskIn.MigratedTotal, Files: len(g.Files), Lines: g.Insertions + g.Deletions}
		for _, name := range g.Dependencies {
			if d, ok := byDep[name]; ok {
				in.Deps = append(in.Deps, d)
				in.Regressed = append(in.Regressed, d.Regressed...)
			}
		}
		if g.Index < n {
			in.StackNote = fmt.Sprintf("Part %d of %d: the sandbox tested all parts together, not this part on its own; merge the parts in order", g.Index, n)
		}
		risk := assessPRRisk(in)

		var commits []prCommit
		for _, f := range g.Files {
			c := prCommit{Message: fmt.Sprintf("Update %s for %s", f.Path, strings.Join(g.Dependencies, ", ")) +
				fmt.Sprintf("\n\nGenerated by DepExit (part %d of %d of a stacked migration).", g.Index, n), Files: []string{f.Path}}
			if f.Source == "split" {
				c.Sources = map[string]string{f.Path: filepath.Join(dir, "split", fmt.Sprint(g.Index), filepath.FromSlash(f.Path))}
			}
			commits = append(commits, c)
		}
		files := make([]string, 0, len(g.Files))
		for _, f := range g.Files {
			files = append(files, f.Path)
		}

		var b strings.Builder
		fmt.Fprintf(&b, "## Part %d of %d · %s\n\n", g.Index, n, g.Title)
		if g.Index == 1 {
			fmt.Fprintf(&b, "First part of a stacked migration: **merge this one first.**\n\n")
		} else {
			fmt.Fprintf(&b, "Stacked on part %d: this PR shows only its own change. **Merge the earlier parts first**; "+
				"GitHub then retargets this PR to the default branch.\n\n", g.Index-1)
		}
		fmt.Fprintf(&b, "| Dependency | Change |\n|---|---|\n")
		for _, name := range g.Dependencies {
			fmt.Fprintf(&b, "| `%s` | %s |\n", name, mdEscape(byDep[name].Strategy))
		}
		fmt.Fprintf(&b, "\n%d file(s), +%d / -%d lines · removes %d dependency-risk points.\n\n",
			len(g.Files), g.Insertions, g.Deletions, g.RiskReduction)
		fmt.Fprintf(&b, "### All parts\n\n%s\n\n", stackPlaceholder)
		fmt.Fprintf(&b, "### Verification\n\n%s The full Exit Capsule is in the description of part 1.\n", sp.Note)
		body := b.String()
		if g.Index == 1 { // the first part carries the full capsule
			body += "\n---\n\n" + single.bodyRest
		}
		st.PRs = append(st.PRs, &prPlan{
			Owner: single.Owner, Repo: single.Repo, BaseCommit: single.BaseCommit,
			Branch: fmt.Sprintf("%s-part%d", single.Branch, g.Index),
			Title:  fmt.Sprintf("DepExit (%d/%d): %s", g.Index, n, g.Title),
			Body:   prRiskMarkdown(risk, risk.ForceDraft) + body, Commits: commits, FilesChanged: files,
			Risk: risk, bodyRest: body,
		})
	}
	return st
}

// stackNeedsConfirm reports whether any part has a high review risk.
func (st *prStack) needsConfirm() bool {
	for _, p := range st.PRs {
		if p.Risk.RequireConfirm {
			return true
		}
	}
	return false
}

// createStack pushes every part on top of the previous one and opens one PR per part.
func (a *API) createStack(ctx context.Context, id string, st *prStack, token string, draft bool) (*prResult, error) {
	gh := &ghClient{base: githubAPIBase(), token: token, http: &http.Client{Timeout: 30 * time.Second}}
	first := st.PRs[0]
	t, err := a.resolveTarget(ctx, gh, first)
	if err != nil {
		return nil, err
	}
	if t.forked {
		return nil, errSplitNeedsPush{repo: first.Owner + "/" + first.Repo}
	}
	migRoot := filepath.Join(a.store.jobDir(id), "runs", "migrated", "repo")
	parent, base := first.BaseCommit, t.defaultBranch
	var results []prResult
	for _, p := range st.PRs {
		head, err := a.pushCommits(ctx, t, migRoot, parent, p.Commits)
		if err != nil {
			return nil, fmt.Errorf("part %s: %w", p.Title, err)
		}
		if err := a.setBranch(ctx, t, p.Branch, head); err != nil {
			return nil, err
		}
		d := draft || p.Risk.ForceDraft
		p.Body = prRiskMarkdown(p.Risk, d) + p.bodyRest
		res, err := a.openPR(ctx, t, p, base, d)
		if err != nil {
			return nil, fmt.Errorf("part %s: %w", p.Title, err)
		}
		res.Title = p.Title
		results = append(results, *res)
		parent, base = head, p.Branch
	}
	// now that every PR has a number, link the parts to each other
	var list strings.Builder
	for i, r := range results {
		fmt.Fprintf(&list, "%d. #%d %s\n", i+1, r.Number, mdEscape(r.Title))
	}
	for i, r := range results {
		body := strings.Replace(prRiskMarkdown(st.PRs[i].Risk, r.Draft)+st.PRs[i].bodyRest, stackPlaceholder, list.String(), 1)
		_ = gh.do(ctx, "PATCH", fmt.Sprintf("/repos/%s/%s/pulls/%d", first.Owner, first.Repo, r.Number),
			map[string]any{"body": body}, nil) // best effort: the PRs exist either way
	}
	out := results[0]
	out.Stack = results
	return &out, nil
}
